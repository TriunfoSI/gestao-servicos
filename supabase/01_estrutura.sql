-- ---------------------------------------------------------------------
-- Equipe e perfis
-- ---------------------------------------------------------------------
create table equipe (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  iniciais        text,
  email           text unique,
  perfil          text check (perfil in ('tecnico','financeiro','coordenacao')),
  formacao        text,
  registro_conselho text,
  cpf             text,
  rg              text,
  ativo           boolean not null default true,
  user_id         uuid unique references auth.users(id) on delete set null,
  criado_em       timestamptz not null default now()
);
comment on column equipe.perfil is 'tecnico = vê só as próprias OS; financeiro = valores; coordenacao = coordenação/diretoria, acesso total. Sem perfil = sem acesso.';

-- ---------------------------------------------------------------------
-- Listas fixas (tabelas de apoio)
-- ---------------------------------------------------------------------
create table servico (
  id        bigint generated by default as identity primary key,
  descricao text not null,
  area      text,
  ativo     boolean not null default true
);

create table os_situacao_detalhe (       -- detalhe da situação técnica (ex.: Aguardando manifestação do órgão)
  id        bigint generated by default as identity primary key,
  descricao text not null,
  ativo     boolean not null default true
);

create table periodo (                   -- blocos de previsão: meses, bimestres, semestres...
  id        bigint generated by default as identity primary key,
  descricao text not null
);

create table mov_tipo (
  id        bigint generated by default as identity primary key,
  descricao text not null,
  ativo     boolean not null default true
);

create table mov_detalhe (
  id        bigint generated by default as identity primary key,
  descricao text not null,
  ativo     boolean not null default true
);

create table mov_situacao (
  id        bigint generated by default as identity primary key,
  descricao text not null,
  ativo     boolean not null default true
);

-- ---------------------------------------------------------------------
-- Clientes e contatos
-- ---------------------------------------------------------------------
create table cliente (
  id             bigint generated by default as identity primary key,
  nome           text not null,
  nome_reduzido  text,
  cpf_cnpj       text,
  endereco       text,
  municipio      text,
  uf             char(2),
  telefone       text,
  email          text,
  criado_em      timestamptz not null default now()
);

create table contato (                   -- antigo "representante": agora ligado ao cliente
  id             bigint generated by default as identity primary key,
  cliente_id     bigint references cliente(id) on delete set null,
  nome           text not null,
  documentos     text,
  endereco       text,
  municipio      text,
  uf             char(2),
  telefone       text,
  whatsapp       text,
  email          text,
  criado_em      timestamptz not null default now()
);
create index on contato(cliente_id);

-- ---------------------------------------------------------------------
-- Ordem de Serviço
-- ---------------------------------------------------------------------
create table os (
  id                    bigint generated by default as identity primary key,
  numero                text,
  proposta              text,
  titulo                text,
  cliente_id            bigint not null references cliente(id),
  contato_id            bigint references contato(id) on delete set null,
  responsavel_id        bigint references equipe(id) on delete set null,
  data_aceite           date,
  tipo_aceite           text,
  data_termino          date,
  prazo_contratual      text,
  local                 text,
  local_endereco        text,
  municipio             text,
  uf                    char(2),
  codigo_cliente        text,
  dropbox_url           text,
  sit_tecnica           text not null default 'Não iniciado'
                        check (sit_tecnica in ('Não iniciado','Em andamento','Paralisado','Finalizado','Cancelado')),
  sit_tecnica_detalhe_id bigint references os_situacao_detalhe(id),
  sit_comercial         text not null default 'Em aberto'
                        check (sit_comercial in ('Em aberto','Paralisado','Encerrado')),
  -- Contrato é calculado: só encerra quando a parte técnica E a comercial estiverem encerradas
  sit_contrato          text generated always as (
                          case
                            when sit_tecnica in ('Finalizado','Cancelado') and sit_comercial = 'Encerrado' then 'Encerrado'
                            when sit_tecnica = 'Paralisado' or sit_comercial = 'Paralisado' then 'Paralisado'
                            else 'Ativo'
                          end) stored,
  situacao_atualizada_em date,
  revisar_migracao      text,           -- preenchido quando a importação encontrou algo a conferir
  criado_em             timestamptz not null default now(),
  criado_por            uuid default auth.uid(),
  atualizado_em         timestamptz not null default now()
);
create index on os(cliente_id);
create index on os(responsavel_id);

create table os_historico (              -- histórico de mudanças de situação
  id          bigint generated by default as identity primary key,
  os_id       bigint not null references os(id) on delete cascade,
  campo       text not null,
  de          text,
  para        text,
  usuario_id  uuid default auth.uid(),
  em          timestamptz not null default now()
);
create index on os_historico(os_id);

create table os_escopo (
  id          bigint generated by default as identity primary key,
  os_id       bigint not null references os(id) on delete cascade,
  servico_id  bigint references servico(id),
  descricao   text,
  ordem       int not null default 0
);
create index on os_escopo(os_id);

-- ---------------------------------------------------------------------
-- Prazos / cronograma
-- ---------------------------------------------------------------------
create table prazo (
  id             bigint generated by default as identity primary key,
  os_id          bigint not null references os(id) on delete cascade,
  origem         text,                  -- Planejamento, CETESB, MP | Ofício, Prefeitura...
  tipo           text,                  -- Cronograma, Protocolo, Produto técnico, Vencimento, Vistoria técnica
  referencia     text,
  descricao      text not null,
  data_inicio    date,
  qtd_dias       int,
  tipo_dia       text check (tipo_dia in ('úteis','corridos')),
  data_termino   date,
  situacao       text not null default 'Não iniciado'
                 check (situacao in ('Não iniciado','Em andamento','Concluído','Não atendido','Cancelado')),
  periodo_id     bigint references periodo(id),
  responsavel_id bigint references equipe(id) on delete set null,
  criado_em      timestamptz not null default now(),
  criado_por     uuid default auth.uid()
);
create index on prazo(os_id);
create index on prazo(responsavel_id);
create index on prazo(data_termino);

-- ---------------------------------------------------------------------
-- Andamento (movimentações) e tarefas
-- ---------------------------------------------------------------------
create table movimentacao (
  id              bigint generated by default as identity primary key,
  os_id           bigint references os(id) on delete cascade,
  visibilidade    text not null default 'Interna' check (visibilidade in ('Interna','Geral')),
  tipo_id         bigint references mov_tipo(id),
  detalhe_id      bigint references mov_detalhe(id),
  data_inicio     date not null default current_date,
  data_termino    date,
  executor        text,
  descricao       text not null,
  observacao      text,
  situacao_id     bigint references mov_situacao(id),
  responsavel_id  bigint references equipe(id) on delete set null,
  criado_em       timestamptz not null default now(),
  criado_por      uuid default auth.uid()
);
create index on movimentacao(os_id);

create table tarefa (                    -- tarefas definidas na reunião técnica
  id              bigint generated by default as identity primary key,
  os_id           bigint references os(id) on delete cascade,   -- pode ser tarefa geral, sem OS
  descricao       text not null,
  responsavel_id  bigint references equipe(id) on delete set null,
  data_reuniao    date default current_date,
  prazo           date,
  situacao        text not null default 'A fazer'
                  check (situacao in ('A fazer','Em andamento','Aguardando terceiros','Concluída','Cancelada')),
  observacao      text,
  criado_em       timestamptz not null default now(),
  criado_por      uuid default auth.uid(),
  atualizado_em   timestamptz not null default now()
);
create index on tarefa(responsavel_id);
create index on tarefa(os_id);

create table tarefa_atualizacao (        -- o técnico informa a situação à coordenação
  id          bigint generated by default as identity primary key,
  tarefa_id   bigint not null references tarefa(id) on delete cascade,
  situacao    text,
  comentario  text,
  usuario_id  uuid default auth.uid(),
  em          timestamptz not null default now()
);
create index on tarefa_atualizacao(tarefa_id);

-- ---------------------------------------------------------------------
-- Financeiro: parcelas, ajustes comerciais e custos
-- ---------------------------------------------------------------------
create table parcela (
  id                   bigint generated by default as identity primary key,
  os_id                bigint not null references os(id) on delete cascade,
  numero               int,
  total_parcelas       int,
  referencia           text,
  valor                numeric(14,2) not null,
  situacao             text not null default 'Em aberto'
                       check (situacao in ('Em aberto','Nota fiscal emitida','Pago','Pendência','Cancelada')),
  nota_fiscal          text,
  data_prevista        date,
  data_pagamento       date,
  periodo_previsto_id  bigint references periodo(id),
  banco                text,
  observacao           text,
  revisar_migracao     text,
  criado_em            timestamptz not null default now(),
  criado_por           uuid default auth.uid()
);
create index on parcela(os_id);

create table ajuste_comercial (
  id           bigint generated by default as identity primary key,
  os_id        bigint not null references os(id) on delete cascade,
  tipo         text not null check (tipo in ('Desconto','Acréscimo','Cancelamento de parcela','Renegociação','Outro')),
  valor        numeric(14,2) not null default 0,   -- desconto = negativo, acréscimo = positivo
  data         date not null default current_date,
  motivo       text not null,
  aprovado_por text,
  criado_em    timestamptz not null default now(),
  criado_por   uuid default auth.uid()
);
create index on ajuste_comercial(os_id);

create table custo (
  id           bigint generated by default as identity primary key,
  os_id        bigint not null references os(id) on delete cascade,
  tipo         text not null,           -- Terceiros, Deslocamento, Taxa de órgão, Material, Outro
  fornecedor   text,
  descricao    text,
  valor        numeric(14,2) not null,
  data         date,
  situacao     text not null default 'Previsto' check (situacao in ('Previsto','Pago')),
  criado_em    timestamptz not null default now(),
  criado_por   uuid default auth.uid()
);
create index on custo(os_id);

-- ---------------------------------------------------------------------
-- Processos em órgãos e seus acessos
-- ---------------------------------------------------------------------
create table processo (
  id            bigint generated by default as identity primary key,
  os_id         bigint not null references os(id) on delete cascade,
  instituicao   text,
  referencia    text,
  data_abertura date,
  objetivo      text,
  tipo          text check (tipo in ('Digital','Físico')),
  observacao    text,
  criado_em     timestamptz not null default now()
);
create index on processo(os_id);

create table processo_acesso (           -- separado para nunca aparecer no link do cliente
  processo_id  bigint primary key references processo(id) on delete cascade,
  plataforma   text,
  login        text,
  senha        text
);

-- ---------------------------------------------------------------------
-- Produtos técnicos finais (arquivos) e link do cliente
-- ---------------------------------------------------------------------
create table produto_final (
  id            bigint generated by default as identity primary key,
  os_id         bigint not null references os(id) on delete cascade,
  nome          text not null,
  arquivo_path  text not null,          -- caminho no Storage: <os_id>/<arquivo>
  tamanho       bigint,
  enviado_por   uuid default auth.uid(),
  enviado_em    timestamptz not null default now()
);
create index on produto_final(os_id);

create table link_cliente (
  id             bigint generated by default as identity primary key,
  os_id          bigint not null references os(id) on delete cascade,
  token          text not null unique default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  criado_em      timestamptz not null default now(),
  criado_por     uuid default auth.uid(),
  revogado_em    timestamptz,
  ultimo_acesso  timestamptz,
  acessos        int not null default 0
);
create index on link_cliente(os_id);
