-- =====================================================================
-- Ajustes 21/11/2026 — Ordem de serviço
--   1. Link do contrato (Dropbox) na OS: só coordenação/diretoria e
--      financeiro veem e alteram. Fica numa tabela separada, protegida,
--      para o técnico não conseguir ler nem pelo banco.
--   2. Cadastro de atividades do cronograma (atividade_padrao):
--      atividades "Gerais" (aparecem em todas as OS) e atividades de uma
--      categoria (e, se quiser, de uma subcategoria) de OS, com
--      responsável padrão (Triunfo ou Cliente), duração em dias úteis e
--      ordem no cronograma.
--   3. Cronograma: responsável passa a ser "Triunfo" ou "Cliente"
--      (o técnico da Triunfo continua opcional); marca de atividade
--      preliminar (gerada automaticamente, ainda não validada).
--   4. Cronograma preliminar automático: ao definir a categoria da OS
--      (na criação ou depois), se a OS ainda não tem cronograma, o
--      sistema monta um com as atividades Gerais + as da categoria.
--   5. Link do cliente: cronograma mostra o responsável (Triunfo ou
--      Cliente); atividades preliminares só aparecem depois de validadas.
--   6. Situação automática da OS continua considerando o cronograma
--      (inclusive as atividades preliminares e as do cliente).
-- Nenhum dado existente é apagado. Pode ser rodado mais de uma vez.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. LINK DO CONTRATO (só coordenação/diretoria e financeiro)
-- ---------------------------------------------------------------------
create table if not exists os_contrato (
  os_id         bigint primary key references os(id) on delete cascade,
  contrato_url  text,
  atualizado_em timestamptz not null default now(),
  atualizado_por uuid default auth.uid()
);
alter table os_contrato enable row level security;
drop policy if exists financeiro_gestor on os_contrato;
create policy financeiro_gestor on os_contrato for all to authenticated
  using (e_financeiro()) with check (e_financeiro());
grant select, insert, update, delete on os_contrato to authenticated;
revoke all on os_contrato from anon;

-- ---------------------------------------------------------------------
-- 2. CADASTRO DE ATIVIDADES DO CRONOGRAMA
-- ---------------------------------------------------------------------
create table if not exists atividade_padrao (
  id              bigint generated by default as identity primary key,
  descricao       text not null,
  categoria_id    bigint references os_categoria(id) on delete cascade,     -- vazio = Geral (todas as OS)
  subcategoria_id bigint references os_subcategoria(id) on delete set null, -- opcional
  responsavel     text not null default 'Triunfo' check (responsavel in ('Triunfo','Cliente')),
  duracao_dias    int  not null default 5 check (duracao_dias > 0),          -- dias úteis
  ordem           int  not null default 500,                                 -- posição no cronograma preliminar
  ativo           boolean not null default true
);
create unique index if not exists atividade_padrao_unica
  on atividade_padrao (lower(descricao), coalesce(categoria_id, 0), coalesce(subcategoria_id, 0));

alter table atividade_padrao enable row level security;
drop policy if exists ler on atividade_padrao;
drop policy if exists gerir on atividade_padrao;
create policy ler on atividade_padrao for select to authenticated using (tem_acesso());
create policy gerir on atividade_padrao for all to authenticated using (e_gestor()) with check (e_gestor());
grant select, insert, update, delete on atividade_padrao to authenticated;
revoke all on atividade_padrao from anon;

