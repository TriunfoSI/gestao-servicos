-- ---------------------------------------------------------------------
-- 3. CRONOGRAMA: responsável Triunfo/Cliente e atividade preliminar
-- ---------------------------------------------------------------------
alter table cronograma add column if not exists responsavel_parte text not null default 'Triunfo';
alter table cronograma drop constraint if exists cronograma_responsavel_parte_check;
alter table cronograma add constraint cronograma_responsavel_parte_check check (responsavel_parte in ('Triunfo','Cliente'));
alter table cronograma add column if not exists atividade_id bigint references atividade_padrao(id) on delete set null;
alter table cronograma add column if not exists preliminar boolean not null default false;

-- técnico que só tem a atividade atribuída (não edita a OS) continua mudando só situação e observação
create or replace function cronograma_restringir_tecnico() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not pode_editar_os(old.os_id) then
    if new.descricao is distinct from old.descricao or new.os_id is distinct from old.os_id
       or new.data_inicio is distinct from old.data_inicio or new.data_termino is distinct from old.data_termino
       or new.responsavel_id is distinct from old.responsavel_id or new.periodo_id is distinct from old.periodo_id
       or new.responsavel_parte is distinct from old.responsavel_parte or new.preliminar is distinct from old.preliminar then
      raise exception 'Você só pode alterar a situação e a observação desta atividade.';
    end if;
  end if;
  return new;
end $$;

drop view if exists v_cronograma;
create view v_cronograma with (security_invoker = true) as
select g.*,
       o.numero  as os_numero,
       o.titulo  as os_titulo,
       o.responsavel_id as os_responsavel_id,
       coalesce(c.nome_reduzido, c.nome) as cliente_curto,
       e.nome    as responsavel_nome,
       e.iniciais as responsavel_iniciais,
       pe.descricao as periodo,
       (g.situacao <> 'Concluída' and g.data_termino < current_date) as atrasada
  from cronograma g
  join os o on o.id = g.os_id
  join cliente c on c.id = o.cliente_id
  left join equipe e on e.id = g.responsavel_id
  left join periodo pe on pe.id = g.periodo_id;
grant select on v_cronograma to authenticated;
revoke all on v_cronograma from anon;

-- ---------------------------------------------------------------------
-- 4. CRONOGRAMA PRELIMINAR AUTOMÁTICO
-- ---------------------------------------------------------------------
-- soma N dias úteis (seg a sex) a uma data
create or replace function somar_dias_uteis(p_data date, p_dias int) returns date
language plpgsql immutable as $$
declare d date := p_data; n int := 0;
begin
  if p_data is null then return null; end if;
  while n < coalesce(p_dias, 0) loop
    d := d + 1;
    if extract(isodow from d) < 6 then n := n + 1; end if;
  end loop;
  return d;
end $$;

-- Monta o cronograma preliminar da OS: atividades Gerais + as da categoria
-- (e subcategoria) da OS, uma depois da outra, a partir da data do aceite
-- (ou de hoje, se o aceite for antigo ou estiver vazio). Retorna quantas
-- atividades foram incluídas. Respeita as permissões de quem chama.
create or replace function gerar_cronograma_preliminar(p_os bigint) returns int
language plpgsql security invoker set search_path = public as $$
declare o record; a record; inicio date; termino date; qtd int := 0;
begin
  select * into o from os where id = p_os;
  if o.id is null then return 0; end if;
  inicio := greatest(coalesce(o.data_aceite, current_date), current_date);
  while extract(isodow from inicio) > 5 loop inicio := inicio + 1; end loop;   -- começa num dia útil

  for a in
    select * from atividade_padrao ap
     where ap.ativo
       and (ap.categoria_id is null
            or (ap.categoria_id = o.categoria_id and (ap.subcategoria_id is null or ap.subcategoria_id = o.subcategoria_id)))
       and not exists (select 1 from cronograma g where g.os_id = p_os
                        and (g.atividade_id = ap.id or lower(g.descricao) = lower(ap.descricao)))
     order by ap.ordem, ap.id
  loop
    termino := somar_dias_uteis(inicio, a.duracao_dias - 1);
    insert into cronograma (os_id, descricao, data_inicio, data_termino, situacao, responsavel_parte, responsavel_id, atividade_id, preliminar)
    values (p_os, a.descricao, inicio, termino, 'Não iniciada', a.responsavel,
            case when a.responsavel = 'Triunfo' then o.responsavel_id end, a.id, true);
    inicio := somar_dias_uteis(termino, 1);
    qtd := qtd + 1;
  end loop;
  return qtd;
end $$;
revoke all on function gerar_cronograma_preliminar(bigint) from public, anon;
grant execute on function gerar_cronograma_preliminar(bigint) to authenticated;

-- Ao definir a categoria da OS (criação ou alteração), se ela ainda não tem
-- cronograma, gera o preliminar.
create or replace function os_cronograma_preliminar() returns trigger
language plpgsql security invoker set search_path = public as $$
begin
  if new.categoria_id is not null
     and (tg_op = 'INSERT' or new.categoria_id is distinct from old.categoria_id
          or new.subcategoria_id is distinct from old.subcategoria_id)
     and new.sit_contrato is distinct from 'Encerrado'
     and not exists (select 1 from cronograma where os_id = new.id) then
    perform gerar_cronograma_preliminar(new.id);
  end if;
  return null;
end $$;
drop trigger if exists os_cronograma_preliminar on os;
create trigger os_cronograma_preliminar after insert or update of categoria_id, subcategoria_id on os
  for each row execute function os_cronograma_preliminar();

-- ---------------------------------------------------------------------
-- 6. SITUAÇÃO AUTOMÁTICA DA OS (mesma regra do script de 21/11; só
--    passa a dizer quando a atividade atrasada é do cliente)
-- ---------------------------------------------------------------------
drop view if exists v_os_situacao;
drop view if exists v_os_alerta;
create view v_os_alerta with (security_invoker = true) as
select p.os_id, 'Prazo'::text as origem, p.descricao, p.data_termino as data
  from prazo p
 where not p.atendido and p.data_termino is not null
union all
select g.os_id, 'Cronograma',
       g.descricao || case when g.responsavel_parte = 'Cliente' then ' (ação do cliente)' else '' end,
       g.data_termino
  from cronograma g
 where g.situacao <> 'Concluída' and g.data_termino is not null
union all
select pr.os_id, 'Verificação',
       concat_ws(' — ', pr.natureza, pr.instituicao, pr.referencia), pr.proxima_verificacao
  from processo pr
 where pr.proxima_verificacao is not null
union all
select t.os_id, 'Tarefa', t.descricao, t.prazo
  from tarefa t
 where t.os_id is not null and t.prazo is not null and t.situacao not in ('Concluída','Cancelada')
union all
select pa.os_id, 'Parcela',
       concat_ws(' ', 'Parcela', pa.numero::text || coalesce('/' || pa.total_parcelas::text, ''), nullif(pa.referencia, '')),
       pa.data_prevista
  from parcela pa
 where pa.situacao not in ('Pago','Cancelada') and pa.data_prevista < current_date;

create view v_os_situacao with (security_invoker = true) as
with itens as (
  select a.*,
         case when a.data < current_date then 'Vencido'
              when a.data <= current_date + 10 then 'A vencer' end as estado
    from v_os_alerta a
)
select o.id as os_id,
       o.numero as os_numero,
       o.titulo as os_titulo,
       o.responsavel_id,
       coalesce(c.nome_reduzido, c.nome) as cliente_curto,
       c.nome as cliente_nome,
       e.iniciais as responsavel_iniciais,
       count(i.*) filter (where i.estado = 'Vencido')  as qtd_vencidos,
       count(i.*) filter (where i.estado = 'A vencer') as qtd_a_vencer,
       case when count(i.*) filter (where i.estado = 'Vencido') > 0 then 'Pendência'
            when count(i.*) filter (where i.estado = 'A vencer') > 0 then 'Prazos a vencer'
            else 'Em conformidade' end as situacao,
       min(i.data) filter (where i.estado is not null) as data_mais_proxima,
       coalesce(jsonb_agg(jsonb_build_object('origem', i.origem, 'descricao', i.descricao, 'data', i.data, 'estado', i.estado)
                          order by i.data) filter (where i.estado is not null), '[]') as itens
  from os o
  join cliente c on c.id = o.cliente_id
  left join equipe e on e.id = o.responsavel_id
  left join itens i on i.os_id = o.id
 where o.sit_contrato is distinct from 'Encerrado'
 group by o.id, o.numero, o.titulo, o.responsavel_id, c.nome_reduzido, c.nome, e.iniciais;

grant select on v_os_alerta, v_os_situacao to authenticated;
revoke all on v_os_alerta, v_os_situacao from anon;

-- ---------------------------------------------------------------------
-- 5. RELATÓRIO DO CLIENTE: responsável de cada atividade; preliminares
--    (ainda não validadas pelo técnico) não aparecem
-- ---------------------------------------------------------------------
create or replace function relatorio_cliente(p_token text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_os bigint; r jsonb;
begin
  select os_id into v_os from link_cliente
   where token = p_token and revogado_em is null;
  if v_os is null then
    return jsonb_build_object('erro', 'Link inválido ou cancelado.');
  end if;
  update link_cliente set ultimo_acesso = now(), acessos = acessos + 1 where token = p_token;

  select jsonb_build_object(
    'os', (select jsonb_build_object(
              'numero', o.numero, 'titulo', o.titulo, 'proposta', o.proposta,
              'cliente', c.nome, 'local', o.local, 'local_endereco', o.local_endereco,
              'municipio', o.municipio, 'uf', o.uf, 'data_aceite', o.data_aceite,
              'data_termino', o.data_termino, 'prazo_contratual', o.prazo_contratual,
              'sit_tecnica', o.sit_tecnica, 'sit_tecnica_detalhe', d.descricao,
              'sit_comercial', o.sit_comercial, 'sit_contrato', o.sit_contrato,
              'responsavel', e.nome, 'atualizado', o.situacao_atualizada_em)
             from os o join cliente c on c.id = o.cliente_id
             left join equipe e on e.id = o.responsavel_id
             left join os_situacao_detalhe d on d.id = o.sit_tecnica_detalhe_id
            where o.id = v_os),
    'escopo', coalesce((select jsonb_agg(jsonb_build_object('servico', s.descricao, 'descricao', x.descricao) order by x.ordem, x.id)
             from os_escopo x left join servico s on s.id = x.servico_id where x.os_id = v_os), '[]'),
    'cronograma', coalesce((select jsonb_agg(jsonb_build_object('descricao', g.descricao,
                    'inicio', g.data_inicio, 'termino', g.data_termino, 'situacao', g.situacao,
                    'responsavel', g.responsavel_parte) order by g.data_inicio nulls last, g.data_termino, g.id)
             from cronograma g where g.os_id = v_os and not g.preliminar), '[]'),
    'prazos', coalesce((select jsonb_agg(jsonb_build_object('descricao', p.descricao, 'tipo', p.tipo, 'origem', p.origem,
                    'data', p.data_termino, 'atendimento', p.data_atendimento,
                    'situacao', prazo_situacao(p.data_termino, p.atendido, p.data_atendimento))
                    order by p.atendido, p.data_termino nulls last, p.id)
             from prazo p where p.os_id = v_os), '[]'),
    'andamento', coalesce((select jsonb_agg(jsonb_build_object('data', m.data_inicio, 'termino', m.data_termino,
                    'detalhe', de.descricao, 'descricao', m.descricao) order by m.data_inicio desc, m.id desc)
             from movimentacao m left join mov_detalhe de on de.id = m.detalhe_id
            where m.os_id = v_os and m.visibilidade = 'Geral'), '[]'),
    'financeiro', coalesce((select jsonb_agg(jsonb_build_object('parcela', concat_ws('/', p.numero, p.total_parcelas),
                    'referencia', p.referencia, 'valor', p.valor, 'situacao', p.situacao,
                    'prevista', p.data_prevista, 'paga', p.data_pagamento, 'nota_fiscal', p.nota_fiscal)
                    order by p.numero nulls last, p.id)
             from parcela p where p.os_id = v_os and p.situacao <> 'Cancelada'), '[]'),
    'processos', coalesce((select jsonb_agg(jsonb_build_object('natureza', pr.natureza, 'instituicao', pr.instituicao, 'referencia', pr.referencia,
                    'abertura', pr.data_abertura, 'objetivo', pr.objetivo, 'tipo', pr.tipo,
                    'verificado_em', pr.verificado_em, 'situacao', pr.situacao) order by pr.data_abertura nulls last)
             from processo pr where pr.os_id = v_os), '[]'),
    'produtos', coalesce((select jsonb_agg(jsonb_build_object('nome', f.nome, 'tipo', t.descricao, 'numero', f.numero,
                    'data', coalesce(f.data_elaboracao, f.enviado_em::date), 'enviado_em', f.enviado_em)
                    order by coalesce(f.data_elaboracao, f.enviado_em::date))
             from produto_final f left join tipo_produto_tecnico t on t.id = f.tipo_id where f.os_id = v_os), '[]')
  ) into r;
  return r;
end $$;

revoke all on function relatorio_cliente(text) from public;
grant execute on function relatorio_cliente(text) to anon, authenticated;

grant usage, select on all sequences in schema public to authenticated;
