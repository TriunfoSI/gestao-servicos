-- =====================================================================
-- Ajuste 17/11/2026: separa CRONOGRAMA (atividades com período) de PRAZOS (datas únicas)
--  * cronograma: atividades para cumprir o escopo técnico da OS
--      situação: Não iniciada | Em andamento | Concluída
--  * prazo: datas únicas (prazo de órgão, comunique-se, entrega de produto,
--      vencimento de contrato...). Situação calculada pela data: A vencer | Vencido
--  Os registros de prazo do tipo "Cronograma" passam para a nova tabela.
--  Pode ser rodado mais de uma vez sem duplicar nada.
-- =====================================================================

create table if not exists cronograma (
  id             bigint generated by default as identity primary key,
  os_id          bigint not null references os(id) on delete cascade,
  descricao      text not null,
  data_inicio    date,
  data_termino   date,
  situacao       text not null default 'Não iniciada'
                 check (situacao in ('Não iniciada','Em andamento','Concluída')),
  responsavel_id bigint references equipe(id) on delete set null,
  periodo_id     bigint references periodo(id),
  observacao     text,
  criado_em      timestamptz not null default now(),
  criado_por     uuid default auth.uid(),
  check (data_termino is null or data_inicio is null or data_termino >= data_inicio)
);
create index if not exists cronograma_os_idx on cronograma(os_id);
create index if not exists cronograma_resp_idx on cronograma(responsavel_id);
create index if not exists cronograma_datas_idx on cronograma(data_inicio, data_termino);

-- ---------------------------------------------------------------------
-- Move os prazos do tipo "Cronograma" para a tabela nova
-- ---------------------------------------------------------------------
do $$
begin
  if exists (select 1 from information_schema.columns where table_name = 'prazo' and column_name = 'situacao') then
    insert into cronograma (os_id, descricao, data_inicio, data_termino, situacao, responsavel_id, periodo_id, observacao, criado_em, criado_por)
    select os_id, descricao, data_inicio,
           case when data_inicio is not null and data_termino < data_inicio then data_inicio else data_termino end,
           case situacao when 'Em andamento' then 'Em andamento'
                         when 'Concluído' then 'Concluída'
                         when 'Não atendido' then 'Concluída'
                         when 'Cancelado' then 'Concluída'
                         else 'Não iniciada' end,
           responsavel_id, periodo_id,
           nullif(concat_ws(' | ',
             case when situacao in ('Não atendido','Cancelado') then 'Situação no cadastro antigo: ' || situacao end,
             case when referencia is not null then 'Referência: ' || referencia end,
             case when origem is not null and origem <> 'Planejamento' then 'Origem: ' || origem end), ''),
           criado_em, criado_por
      from prazo where tipo = 'Cronograma';
    delete from prazo where tipo = 'Cronograma';
  end if;
end $$;

-- Prazo deixa de ter situação digitada: ela passa a ser calculada pela data
drop view if exists v_prazo;
drop policy if exists atualizar_meu_prazo on prazo;
alter table prazo drop column if exists situacao;

-- ---------------------------------------------------------------------
-- Quem vê a OS: inclui quem tem atividade do cronograma atribuída
-- ---------------------------------------------------------------------
create or replace function pode_ver_os(p_os bigint) returns boolean
language sql stable security definer set search_path = public as $$
  select case
    when meu_perfil() in ('coordenacao','financeiro') then true
    when meu_perfil() = 'tecnico' then
      exists (select 1 from os where id = p_os and responsavel_id = meu_equipe_id())
      or exists (select 1 from prazo      where os_id = p_os and responsavel_id = meu_equipe_id())
      or exists (select 1 from cronograma where os_id = p_os and responsavel_id = meu_equipe_id())
      or exists (select 1 from tarefa     where os_id = p_os and responsavel_id = meu_equipe_id())
    else false end
$$;

-- ---------------------------------------------------------------------
-- Permissões do cronograma: quem vê a OS lê; coordenação ou responsável pela
-- OS editam; o técnico da atividade pode mudar a situação e a observação.
-- ---------------------------------------------------------------------
alter table cronograma enable row level security;
drop policy if exists ler on cronograma;
drop policy if exists gerir on cronograma;
drop policy if exists atualizar_minha_atividade on cronograma;
create policy ler on cronograma for select to authenticated using (pode_ver_os(os_id));
create policy gerir on cronograma for all to authenticated using (pode_editar_os(os_id)) with check (pode_editar_os(os_id));
create policy atualizar_minha_atividade on cronograma for update to authenticated using (responsavel_id = meu_equipe_id());

create or replace function cronograma_restringir_tecnico() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null and not pode_editar_os(old.os_id) then
    if new.descricao is distinct from old.descricao or new.os_id is distinct from old.os_id
       or new.data_inicio is distinct from old.data_inicio or new.data_termino is distinct from old.data_termino
       or new.responsavel_id is distinct from old.responsavel_id or new.periodo_id is distinct from old.periodo_id then
      raise exception 'Você só pode alterar a situação e a observação desta atividade.';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists cronograma_restringir_tecnico on cronograma;
create trigger cronograma_restringir_tecnico before update on cronograma
  for each row execute function cronograma_restringir_tecnico();

grant select, insert, update, delete on cronograma to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke all on cronograma from anon;

-- ---------------------------------------------------------------------
-- Visões
-- ---------------------------------------------------------------------
create view v_prazo with (security_invoker = true) as
select p.*,
       o.numero  as os_numero,
       o.titulo  as os_titulo,
       o.responsavel_id as os_responsavel_id,
       coalesce(c.nome_reduzido, c.nome) as cliente_curto,
       e.nome    as responsavel_nome,
       e.iniciais as responsavel_iniciais,
       pe.descricao as periodo,
       case when p.data_termino is null then 'Sem data'
            when p.data_termino < current_date then 'Vencido'
            else 'A vencer' end as situacao,
       p.data_termino - current_date as dias_restantes
  from prazo p
  join os o on o.id = p.os_id
  join cliente c on c.id = o.cliente_id
  left join equipe e on e.id = p.responsavel_id
  left join periodo pe on pe.id = p.periodo_id;

drop view if exists v_cronograma;
create view v_cronograma with (security_invoker = true) as
select g.*,
       o.numero  as os_numero,
       o.titulo  as os_titulo,
       o.responsavel_id as os_responsavel_id,
       coalesce(c.nome_reduzido, c.nome) as cliente_curto,
       e.nome    as responsavel_nome,
       e.iniciais as responsavel_iniciais,
       pe.descricao as periodo,
       (g.situacao <> 'Concluída' and g.data_termino < current_date) as atrasada
  from cronograma g
  join os o on o.id = g.os_id
  join cliente c on c.id = o.cliente_id
  left join equipe e on e.id = g.responsavel_id
  left join periodo pe on pe.id = g.periodo_id;

grant select on v_prazo, v_cronograma to authenticated;
revoke all on v_prazo, v_cronograma from anon;

-- ---------------------------------------------------------------------
-- Relatório do cliente: cronograma e prazos em blocos separados
-- ---------------------------------------------------------------------
create or replace function relatorio_cliente(p_token text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_os bigint; r jsonb;
begin
  select os_id into v_os from link_cliente
   where token = p_token and revogado_em is null;
  if v_os is null then
    return jsonb_build_object('erro', 'Link inválido ou cancelado.');
  end if;
  update link_cliente set ultimo_acesso = now(), acessos = acessos + 1 where token = p_token;

  select jsonb_build_object(
    'os', (select jsonb_build_object(
              'numero', o.numero, 'titulo', o.titulo, 'proposta', o.proposta,
              'cliente', c.nome, 'local', o.local, 'local_endereco', o.local_endereco,
              'municipio', o.municipio, 'uf', o.uf, 'data_aceite', o.data_aceite,
              'data_termino', o.data_termino, 'prazo_contratual', o.prazo_contratual,
              'sit_tecnica', o.sit_tecnica, 'sit_tecnica_detalhe', d.descricao,
              'sit_comercial', o.sit_comercial, 'sit_contrato', o.sit_contrato,
              'responsavel', e.nome, 'atualizado', o.situacao_atualizada_em)
             from os o join cliente c on c.id = o.cliente_id
             left join equipe e on e.id = o.responsavel_id
             left join os_situacao_detalhe d on d.id = o.sit_tecnica_detalhe_id
            where o.id = v_os),
    'escopo', coalesce((select jsonb_agg(jsonb_build_object('servico', s.descricao, 'descricao', x.descricao) order by x.ordem, x.id)
             from os_escopo x left join servico s on s.id = x.servico_id where x.os_id = v_os), '[]'),
    'cronograma', coalesce((select jsonb_agg(jsonb_build_object('descricao', g.descricao,
                    'inicio', g.data_inicio, 'termino', g.data_termino, 'situacao', g.situacao) order by g.data_inicio nulls last, g.data_termino, g.id)
             from cronograma g where g.os_id = v_os), '[]'),
    'prazos', coalesce((select jsonb_agg(jsonb_build_object('descricao', p.descricao, 'tipo', p.tipo, 'origem', p.origem,
                    'data', p.data_termino,
                    'situacao', case when p.data_termino is null then 'Sem data' when p.data_termino < current_date then 'Vencido' else 'A vencer' end)
                    order by p.data_termino nulls last, p.id)
             from prazo p where p.os_id = v_os), '[]'),
    'andamento', coalesce((select jsonb_agg(jsonb_build_object('data', m.data_inicio, 'termino', m.data_termino,
                    'detalhe', de.descricao, 'descricao', m.descricao) order by m.data_inicio desc, m.id desc)
             from movimentacao m left join mov_detalhe de on de.id = m.detalhe_id
            where m.os_id = v_os and m.visibilidade = 'Geral'), '[]'),
    'financeiro', coalesce((select jsonb_agg(jsonb_build_object('parcela', concat_ws('/', p.numero, p.total_parcelas),
                    'referencia', p.referencia, 'valor', p.valor, 'situacao', p.situacao,
                    'prevista', p.data_prevista, 'paga', p.data_pagamento, 'nota_fiscal', p.nota_fiscal)
                    order by p.numero nulls last, p.id)
             from parcela p where p.os_id = v_os and p.situacao <> 'Cancelada'), '[]'),
    'processos', coalesce((select jsonb_agg(jsonb_build_object('instituicao', pr.instituicao, 'referencia', pr.referencia,
                    'abertura', pr.data_abertura, 'objetivo', pr.objetivo, 'tipo', pr.tipo) order by pr.data_abertura nulls last)
             from processo pr where pr.os_id = v_os), '[]'),
    'produtos', coalesce((select jsonb_agg(jsonb_build_object('nome', f.nome, 'enviado_em', f.enviado_em) order by f.enviado_em)
             from produto_final f where f.os_id = v_os), '[]')
  ) into r;
  return r;
end $$;
