-- Ajuste 27/11/2026: formulário público de SOLICITAÇÃO DE PROPOSTA
--   - O cliente recebe o link .../proposta.html, preenche os dados mínimos
--     e envia arquivos. Nada é lido de volta pelo link: quem abre a página
--     só consegue ENVIAR a própria solicitação.
--   - As solicitações aparecem no sistema em "Propostas" (só para a equipe).
--   - Arquivos vão para a pasta privada "solicitacoes-proposta" do Storage,
--     até 20 MB cada, só nos formatos aceitos, no máximo 30 por solicitação
--     e só nas 2 horas seguintes ao envio do formulário.
--   - Proteção contra abuso: no máximo 20 envios a cada 10 minutos no total.
-- Rodar depois do 17_documentos_processos. Pode ser rodado mais de uma vez.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. Tabela das solicitações
-- ---------------------------------------------------------------------
create table if not exists solicitacao_proposta (
  id                    bigint generated by default as identity primary key,
  protocolo             text unique,
  token                 uuid not null unique default gen_random_uuid(),  -- nome da pasta dos arquivos
  contratante_nome      text not null,
  contratante_endereco  text,
  contratante_cpf_cnpj  text,
  contratante_email     text not null,
  contratante_telefone  text not null,
  local_denominacao     text,
  local_endereco        text,
  local_link_mapa       text,
  descricao             text not null,
  aceite_lgpd           boolean not null default false,
  situacao              text not null default 'Nova'
                        check (situacao in ('Nova','Em análise','Proposta enviada','Arquivada')),
  observacao            text,                         -- anotação interna da equipe
  criado_em             timestamptz not null default now(),
  atualizado_em         timestamptz not null default now()
);
create index if not exists solicitacao_proposta_criado_em on solicitacao_proposta(criado_em);

alter table solicitacao_proposta enable row level security;
drop policy if exists ler on solicitacao_proposta;
drop policy if exists alterar on solicitacao_proposta;
drop policy if exists excluir on solicitacao_proposta;
create policy ler     on solicitacao_proposta for select to authenticated using (tem_acesso());
create policy alterar on solicitacao_proposta for update to authenticated using (tem_acesso()) with check (tem_acesso());
create policy excluir on solicitacao_proposta for delete to authenticated using (e_gestor());
-- ninguém de fora lê ou grava direto na tabela: o formulário usa a função abaixo
revoke all on solicitacao_proposta from anon;

create or replace function solicitacao_proposta_atualizado() returns trigger
language plpgsql as $$ begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists solicitacao_proposta_atualizado on solicitacao_proposta;
create trigger solicitacao_proposta_atualizado before update on solicitacao_proposta
  for each row execute function solicitacao_proposta_atualizado();

-- ---------------------------------------------------------------------
-- 2. Envio pelo formulário público (único caminho de gravação para quem
--    não tem login). Valida os campos e devolve protocolo + pasta.
-- ---------------------------------------------------------------------
create or replace function enviar_solicitacao_proposta(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_txt text;
  r solicitacao_proposta;
  f text;
begin
  -- campo-isca: pessoas não veem; robôs costumam preencher
  if coalesce(p->>'site', '') <> '' then
    return jsonb_build_object('erro', 'Não foi possível enviar.');
  end if;

  if (select count(*) from solicitacao_proposta where criado_em > now() - interval '10 minutes') >= 20 then
    return jsonb_build_object('erro', 'Recebemos muitas solicitações agora. Tente novamente em alguns minutos.');
  end if;

  foreach f in array array['contratante_nome','contratante_endereco','contratante_cpf_cnpj','contratante_email',
                           'contratante_telefone','local_denominacao','local_endereco','descricao'] loop
    if coalesce(trim(p->>f), '') = '' then
      return jsonb_build_object('erro', 'Preencha todos os campos obrigatórios.');
    end if;
  end loop;

  foreach f in array array['contratante_nome','contratante_endereco','contratante_cpf_cnpj','contratante_email',
                           'contratante_telefone','local_denominacao','local_endereco','local_link_mapa'] loop
    if length(coalesce(p->>f, '')) > 500 then
      return jsonb_build_object('erro', 'Algum campo ficou longo demais. Resuma o texto e tente de novo.');
    end if;
  end loop;
  if length(p->>'descricao') > 5000 then
    return jsonb_build_object('erro', 'A descrição ficou longa demais (máximo de 5.000 caracteres).');
  end if;

  v_txt := trim(p->>'contratante_email');
  if v_txt !~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    return jsonb_build_object('erro', 'Confira o e-mail informado.');
  end if;
  if coalesce(trim(p->>'local_link_mapa'), '') <> '' and trim(p->>'local_link_mapa') !~* '^https?://' then
    return jsonb_build_object('erro', 'O link da localização deve começar com http:// ou https://');
  end if;
  if coalesce((p->>'aceite_lgpd')::boolean, false) is not true then
    return jsonb_build_object('erro', 'É preciso autorizar o uso dos dados para enviar.');
  end if;

  insert into solicitacao_proposta (contratante_nome, contratante_endereco, contratante_cpf_cnpj, contratante_email,
    contratante_telefone, local_denominacao, local_endereco, local_link_mapa, descricao, aceite_lgpd)
  values (trim(p->>'contratante_nome'), trim(p->>'contratante_endereco'), trim(p->>'contratante_cpf_cnpj'), v_txt,
    trim(p->>'contratante_telefone'), trim(p->>'local_denominacao'), trim(p->>'local_endereco'),
    nullif(trim(p->>'local_link_mapa'), ''), trim(p->>'descricao'), true)
  returning * into r;

  update solicitacao_proposta
     set protocolo = to_char(r.criado_em at time zone 'America/Sao_Paulo', 'YYYY') || '-' || lpad(r.id::text, 4, '0')
   where id = r.id
   returning * into r;

  return jsonb_build_object('protocolo', r.protocolo, 'pasta', r.token);
end $$;

revoke all on function enviar_solicitacao_proposta(jsonb) from public;
grant execute on function enviar_solicitacao_proposta(jsonb) to anon, authenticated;

-- ---------------------------------------------------------------------
-- 3. Arquivos (Storage). Caminho: <pasta da solicitação>/<grupo>/<arquivo>
--    grupos: demanda (ofício, auto de infração...), delimitacao (KMZ, mapa,
--    DWG) e area (matrícula ou outro documento da área).
-- ---------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit)
values ('solicitacoes-proposta', 'solicitacoes-proposta', false, 20971520)   -- até 20 MB por arquivo
on conflict (id) do update set public = false, file_size_limit = 20971520;

create or replace function solicitacao_pode_enviar(p_nome text) returns boolean
language sql stable security definer set search_path = public, storage as $$
  select (storage.foldername(p_nome))[2] in ('demanda','delimitacao','area')
     and array_length(storage.foldername(p_nome), 1) = 2
     and lower(storage.extension(p_nome)) in ('pdf','jpg','jpeg','png','doc','docx','xls','xlsx','dwg','dxf','kml','kmz','zip','rar')
     and exists (select 1 from public.solicitacao_proposta s
                  where s.token::text = (storage.foldername(p_nome))[1]
                    and s.criado_em > now() - interval '2 hours')
     and (select count(*) from storage.objects o
           where o.bucket_id = 'solicitacoes-proposta'
             and o.name like (storage.foldername(p_nome))[1] || '/%') < 30
$$;
revoke all on function solicitacao_pode_enviar(text) from public;
grant execute on function solicitacao_pode_enviar(text) to anon, authenticated;

drop policy if exists "solicitacoes: cliente envia" on storage.objects;
drop policy if exists "solicitacoes: equipe le" on storage.objects;
drop policy if exists "solicitacoes: coordenacao exclui" on storage.objects;
create policy "solicitacoes: cliente envia" on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'solicitacoes-proposta' and public.solicitacao_pode_enviar(name));
create policy "solicitacoes: equipe le" on storage.objects for select to authenticated
  using (bucket_id = 'solicitacoes-proposta' and public.tem_acesso());
create policy "solicitacoes: coordenacao exclui" on storage.objects for delete to authenticated
  using (bucket_id = 'solicitacoes-proposta' and public.e_gestor());

-- Conferência: deve mostrar a tabela e a pasta criadas
select 'solicitacao_proposta' as criado, count(*) as registros from solicitacao_proposta
union all
select 'pasta solicitacoes-proposta', count(*) from storage.buckets where id = 'solicitacoes-proposta';
