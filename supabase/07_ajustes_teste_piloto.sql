create or replace function sem_acento(t text) returns text
language sql immutable as $$
  select lower(translate(coalesce(t, ''),
    'áàâãäéèêëíìîïóòôõöúùûüçñÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑ',
    'aaaaaeeeeiiiiooooouuuucnaaaaaeeeeiiiiooooouuuucn'))
$$;

create or replace function busca_geral(p_termo text, p_areas text[] default null)
returns table (area text, id bigint, os_id bigint, titulo text, detalhe text, data date)
language plpgsql stable security invoker set search_path = public as $$
declare t text := '%' || sem_acento(trim(p_termo)) || '%';
        quer text[] := coalesce(p_areas, array['os','clientes','processos','produtos','tarefas','andamento','prazos','cronograma','fornecedores']);
begin
  if length(trim(coalesce(p_termo, ''))) < 2 then return; end if;

  if 'os' = any(quer) then
    return query
    select 'os'::text, o.id, o.id, concat_ws(' — ', 'OS ' || coalesce(o.numero, '#' || o.id), o.titulo),
           concat_ws(' · ', coalesce(c.nome_reduzido, c.nome), nullif(concat_ws(' > ', ca.descricao, sc.descricao), ''),
                     nullif(o.local, ''), o.sit_contrato, case when not m.no_cadastro then 'encontrado no escopo' end), o.data_aceite
      from os o join cliente c on c.id = o.cliente_id
      left join os_categoria ca on ca.id = o.categoria_id
      left join os_subcategoria sc on sc.id = o.subcategoria_id
      cross join lateral (select sem_acento(concat_ws(' ', o.numero, o.proposta, o.titulo, o.local, o.local_endereco, o.municipio,
                                o.codigo_cliente, c.nome, c.nome_reduzido, ca.descricao, sc.descricao)) like t as no_cadastro) m
     where m.no_cadastro
        or exists (select 1 from os_escopo x where x.os_id = o.id and sem_acento(x.descricao) like t)
     order by o.id desc limit 50;
  end if;

  if 'clientes' = any(quer) then
    return query
    select 'clientes'::text, c.id, null::bigint, coalesce(c.nome_reduzido, c.nome),
           concat_ws(' · ', case when c.nome_reduzido is not null then c.nome end, nullif(c.cpf_cnpj, ''), nullif(c.municipio, '')), null::date
      from cliente c
     where sem_acento(concat_ws(' ', c.nome, c.nome_reduzido, c.cpf_cnpj, c.municipio, c.email, c.telefone)) like t
        or exists (select 1 from contato k where k.cliente_id = c.id and sem_acento(concat_ws(' ', k.nome, k.email, k.telefone)) like t)
     order by c.nome limit 50;
  end if;

  if 'processos' = any(quer) then
    return query
    select 'processos'::text, p.id, p.os_id, concat_ws(' — ', p.natureza, p.instituicao, p.referencia),
           concat_ws(' · ', 'OS ' || o.numero, nullif(p.objetivo, ''), nullif(p.situacao, '')), coalesce(p.verificado_em, p.data_abertura)
      from processo p join os o on o.id = p.os_id
     where sem_acento(concat_ws(' ', p.natureza, p.instituicao, p.referencia, p.objetivo, p.observacao, p.situacao)) like t
     order by p.data_abertura desc nulls last limit 50;
  end if;

  if 'produtos' = any(quer) then
    return query
    select 'produtos'::text, p.id, p.os_id, concat_ws(' — ', tp.descricao, p.nome),
           concat_ws(' · ', 'OS ' || o.numero, nullif(p.numero, ''), nullif(p.descricao, '')), coalesce(p.data_elaboracao, p.enviado_em::date)
      from produto_final p join os o on o.id = p.os_id
      left join tipo_produto_tecnico tp on tp.id = p.tipo_id
     where sem_acento(concat_ws(' ', p.nome, p.numero, p.descricao, tp.descricao)) like t
     order by p.data_elaboracao desc nulls last limit 50;
  end if;

  if 'tarefas' = any(quer) then
    return query
    select 'tarefas'::text, x.id, x.os_id, x.descricao,
           concat_ws(' · ', coalesce('OS ' || o.numero, 'Tarefa geral'), x.situacao), x.prazo
      from tarefa x left join os o on o.id = x.os_id
     where sem_acento(concat_ws(' ', x.descricao, x.observacao, x.orientacao_tecnica)) like t
        or exists (select 1 from tarefa_atualizacao a where a.tarefa_id = x.id and sem_acento(a.comentario) like t)
     order by x.data_reuniao desc nulls last limit 50;
  end if;

  if 'andamento' = any(quer) then
    return query
    select 'andamento'::text, m.id, m.os_id, m.descricao, concat_ws(' · ', 'OS ' || o.numero, m.visibilidade), m.data_inicio
      from movimentacao m left join os o on o.id = m.os_id
     where sem_acento(concat_ws(' ', m.descricao, m.observacao, m.executor)) like t
     order by m.data_inicio desc limit 50;
  end if;

  if 'prazos' = any(quer) then
    return query
    select 'prazos'::text, p.id, p.os_id, p.descricao,
           concat_ws(' · ', 'OS ' || o.numero, nullif(p.tipo, ''), nullif(p.origem, ''), prazo_situacao(p.data_termino, p.atendido, p.data_atendimento)), p.data_termino
      from prazo p join os o on o.id = p.os_id
     where sem_acento(concat_ws(' ', p.descricao, p.referencia, p.tipo, p.origem)) like t
     order by p.data_termino desc nulls last limit 50;
  end if;

  if 'cronograma' = any(quer) then
    return query
    select 'cronograma'::text, g.id, g.os_id, g.descricao, concat_ws(' · ', 'OS ' || o.numero, g.situacao), g.data_inicio
      from cronograma g join os o on o.id = g.os_id
     where sem_acento(concat_ws(' ', g.descricao, g.observacao)) like t
     order by g.data_inicio desc nulls last limit 50;
  end if;

  if 'fornecedores' = any(quer) then
    return query
    select 'fornecedores'::text, f.id, null::bigint, coalesce(f.nome_fantasia, f.nome),
           concat_ws(' · ', (select string_agg(ts.descricao, ', ') from fornecedor_tipo_servico ft
                               join tipo_servico_fornecedor ts on ts.id = ft.tipo_servico_id where ft.fornecedor_id = f.id),
                     f.municipio), null::date
      from fornecedor f
     where sem_acento(concat_ws(' ', f.nome, f.nome_fantasia, f.cpf_cnpj, f.contato, f.municipio, f.observacao)) like t
        or exists (select 1 from fornecedor_tipo_servico ft join tipo_servico_fornecedor ts on ts.id = ft.tipo_servico_id
                    where ft.fornecedor_id = f.id and sem_acento(ts.descricao) like t)
     order by f.nome limit 50;
  end if;
end $$;

