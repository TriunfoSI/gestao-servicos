alter table prazo add column if not exists atendido boolean not null default false;
alter table prazo add column if not exists data_atendimento date;

create or replace function prazo_situacao(p_termino date, p_atendido boolean, p_data_atendimento date) returns text
language sql stable as $$
  select case
    when p_atendido and p_termino is not null and coalesce(p_data_atendimento, p_termino) > p_termino then 'Atendido fora do prazo'
    when p_atendido then 'Atendido'
    when p_termino is null then 'Sem data'
    when p_termino < current_date then 'Vencido'
    else 'A vencer' end
$$;

-- técnico responsável pelo prazo pode marcar como atendido (só esses campos)
drop policy if exists atualizar_meu_prazo on prazo;
create policy atualizar_meu_prazo on prazo for update to authenticated using (responsavel_id = meu_equipe_id());

create or replace function prazo_restringir_tecnico() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'UPDATE' and auth.uid() is not null and not pode_editar_os(old.os_id) then
    if new.descricao is distinct from old.descricao or new.os_id is distinct from old.os_id
       or new.data_termino is distinct from old.data_termino or new.data_inicio is distinct from old.data_inicio
       or new.qtd_dias is distinct from old.qtd_dias or new.responsavel_id is distinct from old.responsavel_id then
      raise exception 'Você só pode marcar este prazo como atendido e informar a data do atendimento.';
    end if;
  end if;
  if not new.atendido then new.data_atendimento := null; end if;
  if new.atendido and new.data_atendimento is null then new.data_atendimento := current_date; end if;
  return new;
end $$;
drop trigger if exists prazo_restringir_tecnico on prazo;
create trigger prazo_restringir_tecnico before insert or update on prazo
  for each row execute function prazo_restringir_tecnico();

drop view if exists v_prazo;
create view v_prazo with (security_invoker = true) as
select p.*,
       o.numero  as os_numero,
       o.titulo  as os_titulo,
       o.responsavel_id as os_responsavel_id,
       coalesce(c.nome_reduzido, c.nome) as cliente_curto,
       e.nome    as responsavel_nome,
       e.iniciais as responsavel_iniciais,
       pe.descricao as periodo,
       prazo_situacao(p.data_termino, p.atendido, p.data_atendimento) as situacao,
       p.data_termino - current_date as dias_restantes
  from prazo p
  join os o on o.id = p.os_id
  join cliente c on c.id = o.cliente_id
  left join equipe e on e.id = p.responsavel_id
  left join periodo pe on pe.id = p.periodo_id;

