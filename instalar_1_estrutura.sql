-- ---------------------------------------------------------------------
-- Ordem de Serviço
-- ---------------------------------------------------------------------
create table os (
  id                    bigint generated by default as identity primary key,
  numero                text,
  proposta              text,
  titulo                text,
  cliente_id            bigint not null references cliente(id),
  contato_id            bigint references contato(id) on delete set null,
  responsavel_id        bigint references equipe(id) on delete set null,
  data_aceite           date,
  tipo_aceite           text,
  data_termino          date,
  prazo_contratual      text,
  local                 text,
  local_endereco        text,
  municipio             text,
  uf                    char(2),
  codigo_cliente        text,
  dropbox_url           text,
  sit_tecnica           text not null default 'Não iniciado'
                        check (sit_tecnica in ('Não iniciado','Em andamento','Paralisado','Finalizado','Cancelado')),
  sit_tecnica_detalhe_id bigint references os_situacao_detalhe(id),
  sit_comercial         text not null default 'Em aberto'
                        check (sit_comercial in ('Em aberto','Paralisado','Encerrado')),
  -- Contrato é calculado: só encerra quando a parte técnica E a comercial estiverem encerradas
  sit_contrato          text generated always as (
                          case
                            when sit_tecnica in ('Finalizado','Cancelado') and sit_comercial = 'Encerrado' then 'Encerrado'
                            when sit_tecnica = 'Paralisado' or sit_comercial = 'Paralisado' then 'Paralisado'
                            else 'Ativo'
                          end) stored,
  situacao_atualizada_em date,
  revisar_migracao      text,           -- preenchido quando a importação encontrou algo a conferir
  criado_em             timestamptz not null default now(),
  criado_por            uuid default auth.uid(),
  atualizado_em         timestamptz not null default now()
);
create index on os(cliente_id);
create index on os(responsavel_id);

create table os_historico (              -- histórico de mudanças de situação
  id          bigint generated by default as identity primary key,
  os_id       bigint not null references os(id) on delete cascade,
  campo       text not null,
  de          text,
  para        text,
  usuario_id  uuid default auth.uid(),
  em          timestamptz not null default now()
);
create index on os_historico(os_id);

