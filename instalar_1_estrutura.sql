-- ---------------------------------------------------------------------
-- Equipe e perfis
-- ---------------------------------------------------------------------
create table equipe (
  id              bigint generated by default as identity primary key,
  nome            text not null,
  iniciais        text,
  email           text unique,
  perfil          text check (perfil in ('tecnico','financeiro','coordenacao')),
  formacao        text,
  registro_conselho text,
  cpf             text,
  rg              text,
  ativo           boolean not null default true,
  user_id         uuid unique references auth.users(id) on delete set null,
  criado_em       timestamptz not null default now()
);
comment on column equipe.perfil is 'tecnico = vê só as próprias OS; financeiro = valores; coordenacao = coordenação/diretoria, acesso total. Sem perfil = sem acesso.';

